"""The 6-DOF dummy wrist: a URDF that chains a fixed base -> prismatic x, y, z -> revolute roll, pitch, yaw -> the
hand's root body, with the hand mounted palm down. Kit-free (the viewer reads the same URDF).

The hand's own links and joints are copied unchanged; mesh paths are made absolute so the generated file can live
anywhere. The mount rotation sits in the yaw joint's origin, not in a fixed joint: the URDF converter merges fixed
joints (merge_fixed_joints=True), which would fold the hand's root body into a dummy link and rename it, breaking
the spec's self-collision pairs and every lookup by the root body's name.
"""
from __future__ import annotations

import json
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
from scipy.spatial.transform import Rotation

REPO = Path(__file__).resolve().parents[2]
WRIST_JOINTS = ("wrist_x", "wrist_y", "wrist_z", "wrist_roll", "wrist_pitch", "wrist_yaw")
_AXES = ((1, 0, 0), (0, 1, 0), (0, 0, 1), (1, 0, 0), (0, 1, 0), (0, 0, 1))
BASE_LINK = "wrist_base"


def palm_frame(spec) -> np.ndarray:
    """The 3x3 whose columns are the palm's axes (normal out of the palm, width, wrist-to-fingertip) in the hand's
    root body frame, from the hand's onboarding JSON next to its URDF."""
    urdf = REPO / spec.urdf_path
    return np.asarray(json.loads(urdf.with_suffix(".spec.json").read_text())["palm_frame"], float)


def palm_down_rotation(frame: np.ndarray) -> np.ndarray:
    """Root-body orientation (in the wrist frame) putting the palm normal along -z and the fingers along +x."""
    x_w = np.array([0.0, 0.0, -1.0])       # palm normal: down, at the table
    z_w = np.array([1.0, 0.0, 0.0])        # wrist -> fingertips
    y_w = np.cross(z_w, x_w)
    R = np.column_stack([x_w, y_w, z_w]) @ frame.T
    assert abs(np.linalg.det(R) - 1.0) < 1e-6, "palm frame is not right-handed"
    return R


def _limits(cfg) -> list[tuple[float, float]]:
    return [cfg.x_range, cfg.y_range, cfg.z_range, cfg.roll_range, cfg.pitch_range, cfg.yaw_range]


def _inertial(mass: float) -> ET.Element:
    el = ET.Element("inertial")
    ET.SubElement(el, "origin", xyz="0 0 0", rpy="0 0 0")
    ET.SubElement(el, "mass", value=f"{mass:g}")
    i = f"{mass * 1e-4:g}"
    ET.SubElement(el, "inertia", ixx=i, ixy="0", ixz="0", iyy=i, iyz="0", izz=i)
    return el


def build_wrist_urdf(spec, cfg, out_path: Path) -> Path:
    """Write ``out_path``: the hand of ``spec`` on the dummy wrist of ``cfg`` (a WristCfg)."""
    src = REPO / spec.urdf_path
    hand = ET.parse(src).getroot()
    for mesh in hand.iter("mesh"):
        f = mesh.get("filename")
        if f and not f.startswith(("package://", "/")):
            mesh.set("filename", str((src.parent / f).resolve()))
    root_link = spec.palm_body_name
    assert hand.find(f"link[@name='{root_link}']") is not None, f"{root_link} is not a link of {src}"

    robot = ET.Element("robot", name=f"{hand.get('name')}_on_wrist")
    robot.append(ET.Comment(f" GENERATED by isaacsimenvs/inhand_olympics/wrist.py from {spec.urdf_path} "))
    links = [BASE_LINK] + [f"{j}_link" for j in WRIST_JOINTS[:-1]]
    for name in links:
        link = ET.SubElement(robot, "link", name=name)
        link.append(_inertial(cfg.link_mass))

    R = palm_down_rotation(palm_frame(spec))
    rpy_mount = Rotation.from_matrix(R).as_euler("xyz")       # URDF rpy: extrinsic x, y, z
    for k, (name, axis, (lo, hi)) in enumerate(zip(WRIST_JOINTS, _AXES, _limits(cfg))):
        prismatic = k < 3
        j = ET.SubElement(robot, "joint", name=name, type="prismatic" if prismatic else "revolute")
        ET.SubElement(j, "parent", link=links[k])
        child = root_link if k == 5 else links[k + 1]
        ET.SubElement(j, "child", link=child)
        if k == 5:
            # The joint frame IS the hand root's frame, so the world-z axis is written in it.
            ET.SubElement(j, "origin", xyz="0 0 0", rpy=" ".join(f"{v:.9f}" for v in rpy_mount))
            axis = tuple(R.T @ np.array(axis, float))
        else:
            ET.SubElement(j, "origin", xyz="0 0 0", rpy="0 0 0")
        ET.SubElement(j, "axis", xyz=" ".join(f"{v:.9f}" for v in axis))
        effort = cfg.prismatic_effort_limit if prismatic else cfg.revolute_effort_limit
        vel = cfg.prismatic_velocity_limit if prismatic else cfg.revolute_velocity_limit
        ET.SubElement(j, "limit", lower=f"{lo:g}", upper=f"{hi:g}", effort=f"{effort:g}", velocity=f"{vel:g}")

    for el in hand:
        if el.tag in ("link", "joint", "material"):
            robot.append(el)
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    ET.ElementTree(robot).write(out_path, encoding="unicode", xml_declaration=True)
    return out_path
