"""One training .sub per reduced Wuji v2 variant, trained from scratch exactly as the full Wuji-only run was.

Same template, observation (canonical palm frame + palm_extents), uniform dynamics, friction 0.5 and RL
configuration as experiments/01oct_uniform_dynamics/make_runs.py --canon; only the robot spec differs -- a variant
from make_missing_fingers.py, registered as wuji2_left_uniform_handonly_<tag>. 5000 epochs, wandb project
gen_mechanics_minimal_embodiment.

    .venv_isaacsim/bin/python experiments/06oct_minimal_embodiment/make_runs.py only_thumb_index only_middle_ring
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "experiments/old_experiments/30sep_ten_hands"))
from make_runs import OBS_LIST, TEMPLATE  # noqa: E402

LOGS = REPO / "debug_outputs/train_logs/06oct_minimal_embodiment"
FRICTION = " env.assets.robot_friction=0.5 env.assets.finger_tip_friction=0.5 env.assets.object_friction=0.5"
CANON_OBS = OBS_LIST.replace("object_vel]", "object_vel,palm_extents]")
CANON = " env.obs.canonical_palm_frame=true"
WANDB = "gen_mechanics_minimal_embodiment"

if __name__ == "__main__":
    for tag in sys.argv[1:]:
        spec = f"wuji2_left_uniform_handonly_{tag}"
        if not (REPO / f"assets/urdf/unified_dynamics_commercial_hands/wuji2/wuji2_left_{tag}.spec.json").exists():
            raise SystemExit(f"no variant {tag}: run make_missing_fingers.py first")
        run = f"wuji2_{tag}"
        text = TEMPLATE.format(hand=f"wuji2 {tag}", run=run, spec=spec, obs=CANON_OBS, logs=LOGS, repo=REPO,
                               hydra_extra=FRICTION + CANON, vlim="")
        text = text.replace("gen_mechanics_ten_hands", WANDB).replace(
            "default configuration, 5000 epochs. Generated by make_runs.py.",
            f"Wuji v2 reduced to '{tag}', uniform dynamics, canonical palm frame + palm_extents, 5000 epochs. "
            "Generated by 06oct_minimal_embodiment/make_runs.py.")
        p = HERE / f"left_{run}.sub"
        p.write_text(text)
        print(p)
