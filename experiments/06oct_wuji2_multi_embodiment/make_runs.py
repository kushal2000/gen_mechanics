"""ONE policy over every Wuji v2 with two or more fingers, left AND right hands: 2 x 26 = 52 embodiments
(ROBOT_SPEC=multi:wuji2_lr_2plus -- robots/multi_hand.py).

Per side: the full hand, the five 4-finger hands (no_<finger>), the ten 3-finger and the ten 2-finger hands
(only_<a>_<b>...), from assets/urdf/unified_dynamics_commercial_hands/make_missing_fingers.py --all. The right
hand is Wuji's own right URDF (unified_commercial_hands/wuji2/vendor_right, same repo and commit as the
left), uniform dynamics like every other hand here; its palm frame is the left's mirror (thumb at +y).

Same RL configuration as experiments/06oct_wuji_5rads (canonical palm frame + palm_extents, friction 0.5,
5 rad/s, the 30sep template's learner), plus the hand-target moving average 0.1 that let the full hand learn
at 5 rad/s (wuji2_full_v5_ema0.1). 12288 envs dealt round-robin: ~236 per hand. One interactive viewer PER
HAND every CAPTURE_VIEWER_INTERVAL epochs (train.py: interactive_viewer/<hand>), and every episode metric
also per hand (per_hand/<hand>_<metric>). Its own wandb project.

Since 7 Oct also action delay on (the default training settings: moving average 0.1 + action delay; see
06oct_wuji_5rads/make_runs.py), so the run is wuji2_lr_2plus_ema0.1_dact. wuji2_lr_2plus_ema0.1.sub, without
it, is what 31826 ran; it is kept as generated rather than rewritten.

    .venv_isaacsim/bin/python experiments/06oct_wuji2_multi_embodiment/make_runs.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "experiments/old_experiments/30sep_ten_hands"))
from make_runs import OBS_LIST, TEMPLATE  # noqa: E402

SPEC = "multi:wuji2_lr_2plus"
LOGS = REPO / "debug_outputs/train_logs/06oct_wuji2_multi_embodiment"
WANDB = "gen_mechanics_wuji2_multi_embodiment"
FRICTION = " env.assets.robot_friction=0.5 env.assets.finger_tip_friction=0.5 env.assets.object_friction=0.5"
CANON_OBS = OBS_LIST.replace("object_vel]", "object_vel,palm_extents]")
HYDRA = FRICTION + " env.obs.canonical_palm_frame=true env.action.hand_moving_average=0.1"
HYDRA += " env.domain_randomization.use_action_delay=true"      # run_rank.sh pins it false; this wins
# 5 rad/s is what the assets carry since 6 Oct; pinned anyway. One viewer per hand x 52 hands: every 500
# epochs rather than common.sh's 250 halves the ~280 MB of viewer HTML a 5000-epoch link would log.
EXPORTS = "export HAND_VELOCITY_LIMIT=5.0\nexport CAPTURE_VIEWER_INTERVAL=\"${CAPTURE_VIEWER_INTERVAL:-500}\"\n"
RUN = "wuji2_lr_2plus_ema0.1_dact"

if __name__ == "__main__":
    text = TEMPLATE.format(hand=RUN, run=RUN, spec=SPEC, obs=CANON_OBS, logs=LOGS, repo=REPO,
                           hydra_extra=HYDRA, vlim=EXPORTS)
    text = text.replace("gen_mechanics_ten_hands", WANDB).replace(
        f"# LEFT {RUN}: in-hand reorientation, default configuration, 5000 epochs. Generated by make_runs.py.",
        "# ONE policy over all 52 Wuji v2 embodiments with >= 2 fingers, left and right (multi:wuji2_lr_2plus), "
        "5 rad/s, moving average 0.1, action delay, canonical palm frame + palm_extents, 5000 epochs per link. "
        "Generated by 06oct_wuji2_multi_embodiment/make_runs.py.")
    text = text.replace(f"left_{RUN}", RUN)          # left AND right hands: no "left_" in the study or log names
    p = HERE / f"{RUN}.sub"
    p.write_text(text)
    print(p)
