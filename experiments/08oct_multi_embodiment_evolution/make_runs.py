"""Multi-embodiment training over Wuji v2 finger-drop families: one policy per family, same RL configuration.

  wuji2_lr_2plus   all 52 hands with two or more fingers, left and right (multi:wuji2_lr_2plus): the full hand,
                   5 four-, 10 three- and 10 two-finger hands per side. 31826's family, rerun with today's defaults.
  wuji2_lr_2to3    only the 40 hands with two or three fingers (multi:wuji2_lr_2to3): the 52 minus the full and
                   the four-finger hands.
  left_wuji2_only_thumb_index_middle, left_wuji2_only_index_middle
                   single-embodiment baselines: one left hand each, trained alone (wuji2_left_uniform_handonly_<tag>),
                   for hands that are also in the families above.

All: the 06oct_wuji2_multi_embodiment configuration (canonical palm frame + palm_extents, friction 0.5, 5 rad/s,
the 30sep template's transformer learner, 12288 envs round-robin over the hands) with the default training
settings since 7 Oct -- hand-target moving average 0.1 AND action delay on (obs and object-state delay off).
Logging since b757927: per-hand metrics as per_hand_metric/<hand>/<metric> over a 1/n_hands window, one
interactive viewer per hand every 10000 env steps (~625 epochs).

    .venv_isaacsim/bin/python experiments/08oct_multi_embodiment_evolution/make_runs.py
    sbatch experiments/08oct_multi_embodiment_evolution/<run>.sub
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "experiments/old_experiments/30sep_ten_hands"))
from make_runs import OBS_LIST, TEMPLATE  # noqa: E402

LOGS = REPO / "debug_outputs/train_logs/08oct_multi_embodiment_evolution"
WANDB = "gen_mechanics_wuji2_multi_embodiment"      # 31826's project, so the curves sit side by side
FRICTION = " env.assets.robot_friction=0.5 env.assets.finger_tip_friction=0.5 env.assets.object_friction=0.5"
CANON_OBS = OBS_LIST.replace("object_vel]", "object_vel,palm_extents]")
HYDRA = FRICTION + " env.obs.canonical_palm_frame=true env.action.hand_moving_average=0.1"
HYDRA += " env.domain_randomization.use_action_delay=true"      # run_rank.sh pins it false; this wins
# The viewer interval counts env steps (16 an epoch); see 06oct_wuji2_multi_embodiment/make_runs.py.
EXPORTS = "export HAND_VELOCITY_LIMIT=5.0\nexport CAPTURE_VIEWER_INTERVAL=\"${CAPTURE_VIEWER_INTERVAL:-10000}\"\n"
SINGLE = ("only_thumb_index_middle", "only_index_middle")       # left hand only
RUNS = {
    "wuji2_lr_2plus": "all 52 Wuji v2 embodiments with >= 2 fingers, left and right",
    "wuji2_lr_2to3": "the 40 Wuji v2 embodiments with 2 or 3 fingers, left and right",
}

if __name__ == "__main__":
    for family, what in RUNS.items():
        run = f"{family}_ema0.1_dact"
        text = TEMPLATE.format(hand=run, run=run, spec=f"multi:{family}", obs=CANON_OBS, logs=LOGS, repo=REPO,
                               hydra_extra=HYDRA, vlim=EXPORTS)
        text = text.replace("gen_mechanics_ten_hands", WANDB).replace(
            f"# LEFT {run}: in-hand reorientation, default configuration, 5000 epochs. Generated by make_runs.py.",
            f"# ONE policy over {what} (multi:{family}), 5 rad/s, moving average 0.1, action delay, canonical "
            "palm frame + palm_extents, 5000 epochs per link. Generated by 08oct_multi_embodiment_evolution/"
            "make_runs.py.")
        text = text.replace(f"left_{run}", run)      # left AND right hands: no "left_" in the study or log names
        p = HERE / f"{run}.sub"
        p.write_text(text)
        print(p)
    for tag in SINGLE:
        run = f"wuji2_{tag}_ema0.1_dact"
        text = TEMPLATE.format(hand=f"wuji2 {tag}", run=run, spec=f"wuji2_left_uniform_handonly_{tag}", obs=CANON_OBS,
                               logs=LOGS, repo=REPO, hydra_extra=HYDRA, vlim=EXPORTS)
        text = text.replace("gen_mechanics_ten_hands", WANDB).replace(
            "default configuration, 5000 epochs. Generated by make_runs.py.",
            f"Wuji v2 reduced to '{tag}' trained alone, 5 rad/s, moving average 0.1, action delay, canonical palm "
            "frame + palm_extents, 5000 epochs. Generated by 08oct_multi_embodiment_evolution/make_runs.py.")
        p = HERE / f"left_{run}.sub"
        p.write_text(text)
        print(p)
