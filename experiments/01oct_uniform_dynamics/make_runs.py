"""One left-hand training .sub per commercial hand and gen-SHARPA, UNIFORM dynamics, default RL configuration, 5000 epochs.

Dynamics from assets/urdf/unified_dynamics_commercial_hands (spec <hand>_left_uniform_handonly): every joint
0.5 N.m / 10 rad/s, stiffness 3.0, damping 0.0775, armature 0.00058; finger links from collision hulls at
1750 kg/m^3; canonical joint conventions. Friction 0.5 on every contact (hand links, fingertips, cube).
Everything else is the ten-hands default (experiments/old_experiments/30sep_ten_hands/make_runs.py): joint transformer d64 /
4 layers, no ghost mask, trimmed observation, no fall penalty, gamma 0.998, adaptive lr from 5e-4,
5 mini-epochs, horizon 16, 5 deg tolerance, joint units "range" (the established encoding).

    .venv_isaacsim/bin/python experiments/01oct_uniform_dynamics/make_runs.py [--canon] [<hand> ...]

--canon: the unified run's observation (experiments/01oct_unified_rl) -- canonical palm frame plus
palm_extents -- written as left_<hand>_uniform_canon.sub, so single-hand and unified runs compare on one
observation.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "experiments/old_experiments/30sep_ten_hands"))
from make_runs import OBS_LIST, TEMPLATE  # noqa: E402  (the ten-hands template, unchanged)

LOGS = REPO / "debug_outputs/train_logs/01oct_uniform_dynamics"
HANDS = ("sharpa", "allegro", "leap", "shadow", "dex3", "tesollo", "wuji2", "xhand", "gen_sharpa")
# gen-SHARPA's dynamics come from the hand generator, so its actuator is set to the uniform one here
# (physics.hand_* overrides); its capsule links keep the generator's density (solid capsules, 2712 kg/m^3).
GEN_SHARPA = f"handonly:{REPO}/assets/populations/sharpa_capsule.json"
UNIFORM_ACTUATOR = (" env.physics.hand_effort_limit=0.5 env.physics.hand_velocity_limit=10.0"
                    " env.physics.hand_stiffness=3.0 env.physics.hand_damping=0.0775 env.physics.hand_armature=0.00058")
FRICTION = " env.assets.robot_friction=0.5 env.assets.finger_tip_friction=0.5 env.assets.object_friction=0.5"
WANDB = "gen_mechanics_uniform_dynamics"
CANON_OBS = OBS_LIST.replace("object_vel]", "object_vel,palm_extents]")
CANON = " env.obs.canonical_palm_frame=true"

if __name__ == "__main__":
    canon = "--canon" in sys.argv
    for hand in [a for a in sys.argv[1:] if a != "--canon"] or HANDS:
        run = f"{hand}_uniform" + ("_canon" if canon else "")
        gen = hand == "gen_sharpa"
        text = TEMPLATE.format(hand=hand, run=run, spec=GEN_SHARPA if gen else f"{hand}_left_uniform_handonly",
                               obs=CANON_OBS if canon else OBS_LIST, logs=LOGS, repo=REPO,
                               hydra_extra=FRICTION + (UNIFORM_ACTUATOR if gen else "") + (CANON if canon else ""),
                               vlim="")
        text = text.replace("gen_mechanics_ten_hands", WANDB).replace(
            "default configuration, 5000 epochs. Generated by make_runs.py.",
            "UNIFORM dynamics, default configuration" + (", canonical palm frame + palm_extents" if canon else "")
            + ", 5000 epochs. Generated by 01oct_uniform_dynamics/make_runs.py.")
        p = HERE / f"left_{run}.sub"
        p.write_text(text)
        print(p)
