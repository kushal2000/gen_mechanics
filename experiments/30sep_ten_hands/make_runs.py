"""Write one left-hand training .sub per hand: the default configuration, 5000 epochs.

Default (user, 30 Sep): joint transformer d64 / 4 layers / 1 head / ff_mult 2, mu head [64], value head
[512,256], no ghost-action mask, no activation checkpointing; trimmed observation (with the
keypoints_rel_ee fix); no fall penalty; gamma 0.998, adaptive lr from 5e-4, 5 mini-epochs, horizon 16;
5 deg tolerance. Budget 5000 epochs, no chained continuation.

    .venv_isaacsim/bin/python experiments/30sep_ten_hands/make_runs.py [--vlim V] <hand> [...]

--uniform uses the uniform-dynamics spec (<hand>_left_uniform_handonly: 1.0 N.m, 10 rad/s, gen-SHARPA gains,
1750 kg/m^3 links) and 0.5 friction on every contact, and suffixes the run _uniform.
--vlim V caps every hand joint's speed at V rad/s in the solver (physics.hand_velocity_limit) and
suffixes the run _v<V>. Without it the vendor URDF's per-joint caps apply (2.0 Shadow .. 15 SHARPA).
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
LOGS = REPO / "debug_outputs/train_logs/30sep_ten_hands"
# hand -> ROBOT_SPEC for the LEFT hand. Filled in as each hand is integrated.
LEFT = {
    "sharpa": "sharpa_handonly",
    "gen_sharpa": "handonly:/share/portal/kk837/gen_mechanics/assets/populations/sharpa_capsule.json",
    # onboarded by assets/urdf/unified_commercial_hands/onboard.py (robots/unified_hands.py)
    **{h: f"{h}_left_handonly" for h in ("allegro", "leap", "shadow", "dex3", "tesollo", "wuji2", "xhand")},
}
# Uniform dynamics (assets/urdf/unified_dynamics_commercial_hands): every commercial hand, and one
# friction everywhere -- hand links, fingertips and the cube all 0.5.
UNIFORM = ("sharpa", "allegro", "leap", "shadow", "dex3", "tesollo", "wuji2", "xhand")
UNIFORM_HYDRA = " env.assets.robot_friction=0.5 env.assets.finger_tip_friction=0.5 env.assets.object_friction=0.5"
OBS_LIST = ("[joint_pos,joint_vel,prev_joint_pos,prev_joint_vel,prev_action_targets,joint_link_bbox,"
            "joint_lower,joint_upper,joint_enabled,keypoints_rel_ee,keypoints_rel_goal,object_vel]")

TEMPLATE = """#!/bin/bash
#SBATCH --job-name=L_{run}
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=4
#SBATCH --mem=128000
#SBATCH --time=24:00:00
#SBATCH --partition=portal
#SBATCH --exclude=portal-compute-01
#SBATCH --gres=gpu:1
#SBATCH --signal=B:USR1@900
#SBATCH --output={logs}/left_{run}-%j.log
#SBATCH --error={logs}/left_{run}-%j.err

# LEFT {hand}: in-hand reorientation, default configuration, 5000 epochs. Generated by make_runs.py.
export ARCH=transformer
export OBS_LIST="{obs}"
export USER_HYDRA="agent.params.config.gamma=0.998{hydra_extra}"
export LEARNING_RATE=0.0005 MINI_EPOCHS=5 LR_SCHEDULE=adaptive HORIZON=16
export D_MODEL=64 TRANSFORMER_LAYERS=4 N_HEADS=1 FF_MULT=2
export MU_HEAD_UNITS="[64]" VALUE_HEAD_UNITS="[512,256]"
export GRAD_CHECKPOINT=false MASK_GHOST_ACTIONS=false
{vlim}set -euo pipefail
export ROBOT_SPEC="${{ROBOT_SPEC:-{spec}}}"
export STUDY_ID="${{STUDY_ID:-left_{run}}}"
export SUCCESS_TOLERANCE_DEG=5
export EPOCHS="${{EPOCHS:-5000}}" MAX_CONT="${{MAX_CONT:-1}}" CONT="${{CONT:-1}}"
export WANDB_PROJECT="${{WANDB_PROJECT:-gen_mechanics_ten_hands}}"
export SCALING_RUN_ROOT="${{SCALING_RUN_ROOT:-{logs}}}"

source {repo}/experiments/28sep_inhand_reorientation/common.sh
run_and_chain "$0"
"""

if __name__ == "__main__":
    args, vlim, uniform = sys.argv[1:], None, False
    while args[:1] in (["--vlim"], ["--uniform"]):
        if args[0] == "--vlim":
            vlim, args = args[1], args[2:]
        else:
            uniform, args = True, args[1:]
    for hand in args or (UNIFORM if uniform else LEFT):
        run = hand + ("_uniform" if uniform else "") + (f"_v{vlim}" if vlim else "")
        spec = f"{hand}_left_uniform_handonly" if uniform else LEFT[hand]
        p = HERE / f"left_{run}.sub"
        p.write_text(TEMPLATE.format(hand=hand, run=run, spec=spec, obs=OBS_LIST, logs=LOGS, repo=REPO,
                                     hydra_extra=UNIFORM_HYDRA if uniform else "",
                                     vlim=f"export HAND_VELOCITY_LIMIT={float(vlim)}\n" if vlim else ""))
        print(p)
