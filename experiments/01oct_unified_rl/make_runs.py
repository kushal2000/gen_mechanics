"""The single-policy run over every uniform-dynamics commercial hand (ROBOT_SPEC=multi:uniform).

Same RL configuration as the single-hand runs (experiments/old_experiments/30sep_ten_hands/make_runs.py template): joint
transformer d64 / 4 layers, no ghost mask, trimmed observation, no fall penalty, gamma 0.998, adaptive lr from
5e-4, 5 mini-epochs, horizon 16, 5 deg tolerance; 12288 envs (1536 per hand); friction 0.5 everywhere.

    .venv_isaacsim/bin/python experiments/01oct_unified_rl/make_runs.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "experiments/old_experiments/30sep_ten_hands"))
from make_runs import OBS_LIST, TEMPLATE  # noqa: E402

LOGS = REPO / "debug_outputs/train_logs/01oct_unified_rl"
FRICTION = " env.assets.robot_friction=0.5 env.assets.finger_tip_friction=0.5 env.assets.object_friction=0.5"

# The canonical-palm-frame variant: every hand-relative observation in one frame shared by all hands (x grasp
# normal, y width, z wrist to fingertip, from the palm centre, metres) instead of each vendor's palm-body axes,
# and the palm's size observed directly. Single-hand runs do not need it: one hand, one frame.
CANON_OBS = OBS_LIST.replace("object_vel]", "object_vel,palm_extents]")
CANON_HYDRA = FRICTION + " env.obs.canonical_palm_frame=true"

if __name__ == "__main__":
    for run, obs, extra, blurb in (
            ("multi_uniform", OBS_LIST, FRICTION, ""),
            ("multi_uniform_canon", CANON_OBS, CANON_HYDRA,
             " Canonical palm frame + palm_extents observation.")):
        text = TEMPLATE.format(hand=run, run=run, spec="multi:uniform", obs=obs, logs=LOGS,
                               repo=REPO, hydra_extra=extra, vlim="")
        text = text.replace("gen_mechanics_ten_hands", "gen_mechanics_unified_rl").replace(
            f"# LEFT {run}: in-hand reorientation, default configuration, 5000 epochs. Generated by make_runs.py.",
            "# ONE policy over all 8 uniform-dynamics commercial hands (multi:uniform), default configuration, "
            f"5000 epochs.{blurb} Generated by 01oct_unified_rl/make_runs.py.")
        p = HERE / f"{run}.sub"
        p.write_text(text)
        print(p)
