"""The single-policy run over every uniform-dynamics commercial hand (ROBOT_SPEC=multi:uniform).

Same RL configuration as the single-hand runs (experiments/30sep_ten_hands/make_runs.py template): joint
transformer d64 / 4 layers, no ghost mask, trimmed observation, no fall penalty, gamma 0.998, adaptive lr from
5e-4, 5 mini-epochs, horizon 16, 5 deg tolerance; 12288 envs (1536 per hand); friction 0.5 everywhere.

    .venv_isaacsim/bin/python experiments/01oct_unified_rl/make_runs.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "experiments/30sep_ten_hands"))
from make_runs import OBS_LIST, TEMPLATE  # noqa: E402

LOGS = REPO / "debug_outputs/train_logs/01oct_unified_rl"
FRICTION = " env.assets.robot_friction=0.5 env.assets.finger_tip_friction=0.5 env.assets.object_friction=0.5"

if __name__ == "__main__":
    run = "multi_uniform"
    text = TEMPLATE.format(hand="multi_uniform", run=run, spec="multi:uniform", obs=OBS_LIST, logs=LOGS,
                           repo=REPO, hydra_extra=FRICTION, vlim="")
    text = text.replace("gen_mechanics_ten_hands", "gen_mechanics_unified_rl").replace(
        "# LEFT multi_uniform: in-hand reorientation, default configuration, 5000 epochs. Generated by make_runs.py.",
        "# ONE policy over all 8 uniform-dynamics commercial hands (multi:uniform), default configuration, "
        "5000 epochs. Generated by 01oct_unified_rl/make_runs.py.")
    p = HERE / f"{run}.sub"
    p.write_text(text)
    print(p)
